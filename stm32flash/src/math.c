int16_t twos_compl16(int16_t value){
    return ~(value)+1;
}

int32_t twos_compl32(int32_t value){
    return ~(value)+1;
}

int16_t abs(int16_t value){
    if(value < 0){
        value = twos_compl16(value);
    }
    return value;
}

int32_t abs_32(int32_t value){
    if(value < 0){
        value = twos_compl32(value);
    }
    return value;
}






